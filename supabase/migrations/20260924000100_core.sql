-- Book stock of a tank = SUM(liters) of its movements. Append-only (see guards migration).
create table inventory_movements (
  id          bigint generated always as identity primary key,
  station_id  uuid not null references stations(id),
  tank_id     uuid not null,
  type        movement_type not null,
  liters      numeric(14,3) not null check (liters <> 0),   -- signed: + into tank, - out of tank
  ref_table   text,
  ref_id      uuid,
  reason      text,
  created_by  uuid references auth.users(id),
  created_at  timestamptz not null default now(),
  foreign key (station_id, tank_id) references tanks(station_id, id),
  check (type not in ('adjustment', 'waste') or reason is not null),
  check ((type in ('receipt', 'return', 'transfer_in') and liters > 0)
      or (type in ('sale', 'waste', 'transfer_out') and liters < 0)
      or  type = 'adjustment')
);
create index on inventory_movements (tank_id, created_at);

