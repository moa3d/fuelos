-- =====================================================================
-- FuelOS — core schema
-- Multi-tenant: organization -> stations. Every station-owned row carries station_id.
-- Money: numeric(16,2). Liters: numeric(14,3). Meter readings: numeric(14,1).
-- Client-generated UUIDs are allowed on offline-created rows (shifts, sales).
-- =====================================================================

-- ---------- enums ----------
create type member_role        as enum ('owner', 'accountant', 'shift_manager', 'attendant');
create type platform_role      as enum ('platform_admin', 'support');
create type member_status      as enum ('active', 'invited', 'suspended');
create type station_status     as enum ('setup', 'active', 'suspended');
create type shift_status       as enum ('open', 'submitted', 'approved', 'rejected', 'reopened');
create type payment_method     as enum ('cash', 'card', 'credit', 'voucher');
create type sale_status        as enum ('recorded', 'pending_approval', 'voided');
create type invoice_status     as enum ('pending', 'confirmed', 'corrected', 'cancelled');
create type movement_type      as enum ('receipt', 'sale', 'adjustment', 'waste', 'return', 'transfer_in', 'transfer_out');
create type availability_status as enum ('available', 'limited', 'unavailable');
create type data_source        as enum ('computed', 'manual');
create type account_type       as enum ('asset', 'liability', 'equity', 'revenue', 'expense');
create type entry_status       as enum ('draft', 'posted');
create type period_status      as enum ('open', 'closed');
create type approval_type      as enum ('shift_close', 'credit_over_limit', 'stock_adjustment', 'shift_reopen');
create type approval_status    as enum ('pending', 'approved', 'rejected');
create type company_status     as enum ('active', 'frozen', 'suspended');
create type complaint_kind     as enum ('complaint', 'price_report');
create type complaint_status   as enum ('open', 'awaiting_station', 'resolved', 'escalated');
create type subscription_status as enum ('trial', 'active', 'past_due', 'cancelled', 'legacy');
create type ticket_priority    as enum ('low', 'medium', 'high');
create type ticket_status      as enum ('open', 'in_progress', 'resolved');
create type expense_category   as enum ('salaries', 'utilities', 'maintenance', 'transport', 'other');
create type cash_source        as enum ('cash', 'bank');

-- ---------- tenancy & people ----------
create table organizations (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  created_at  timestamptz not null default now()
);

create table stations (
  id                   uuid primary key default gen_random_uuid(),
  organization_id      uuid not null references organizations(id),
  name                 text not null,
  address              text,
  city                 text,
  timezone             text not null default 'UTC',
  currency_code        char(3) not null,                         -- e.g. 'SYP' (placeholder until confirmed)
  money_decimals       smallint not null default 2 check (money_decimals between 0 and 3),
  status               station_status not null default 'setup',
  -- tolerances (spec: differences above these need a reason + approval)
  cash_tolerance       numeric(16,2) not null default 1000 check (cash_tolerance >= 0),
  stock_tolerance_l    numeric(14,3) not null default 100 check (stock_tolerance_l >= 0),
  max_shift_hours      int not null default 12 check (max_shift_hours > 0),
  default_credit_limit numeric(16,2) not null default 250000 check (default_credit_limit >= 0),
  offline_max_ops      int not null default 50 check (offline_max_ops > 0),
  created_at           timestamptz not null default now()
);
create index on stations (organization_id);

create table platform_staff (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  role       platform_role not null,
  created_at timestamptz not null default now()
);

create table station_members (
  station_id   uuid not null references stations(id) on delete cascade,
  user_id      uuid not null references auth.users(id) on delete cascade,
  role         member_role not null,
  status       member_status not null default 'invited',
  display_name text not null,
  pin_hash     text,                                -- attendants log in with a PIN on a registered device
  created_at   timestamptz not null default now(),
  primary key (station_id, user_id)
);
create index on station_members (user_id);

create table customers (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text,
  phone       text unique,
  created_at  timestamptz not null default now()
);

create table devices (
  id              text primary key,                 -- device identifier generated by the app
  station_id      uuid not null references stations(id) on delete cascade,
  label           text,
  registered_by   uuid references auth.users(id),
  last_sync_at    timestamptz,
  pending_ops     int not null default 0,
  created_at      timestamptz not null default now()
);

-- ---------- catalog: products, tanks, pumps, prices ----------
create table products (
  id          uuid primary key default gen_random_uuid(),
  station_id  uuid not null references stations(id) on delete cascade,
  code        text not null,                        -- 'gasoline_90', 'gasoline_95', 'diesel'
  name        text not null,                        -- display name (Arabic)
  unit        text not null default 'L',
  is_active   boolean not null default true,
  unique (station_id, code),
  unique (station_id, id)
);

create table tanks (
  id             uuid primary key default gen_random_uuid(),
  station_id     uuid not null references stations(id) on delete cascade,
  product_id     uuid not null,
  name           text not null,
  capacity_l     numeric(14,3) not null check (capacity_l > 0),
  min_level_pct  numeric(5,2) not null default 20 check (min_level_pct between 0 and 100),
  is_active      boolean not null default true,
  foreign key (station_id, product_id) references products(station_id, id),
  unique (station_id, id)
);

create table pumps (
  id          uuid primary key default gen_random_uuid(),
  station_id  uuid not null references stations(id) on delete cascade,
  number      int not null check (number > 0),
  name        text,
  is_active   boolean not null default true,
  unique (station_id, number),
  unique (station_id, id)
);

create table nozzles (
  id            uuid primary key default gen_random_uuid(),
  station_id    uuid not null references stations(id) on delete cascade,
  pump_id       uuid not null,
  tank_id       uuid not null,                      -- a nozzle draws from exactly one tank
  label         text not null default '1',
  last_reading  numeric(14,1) not null default 0 check (last_reading >= 0),
  is_active     boolean not null default true,
  foreign key (station_id, pump_id) references pumps(station_id, id),
  foreign key (station_id, tank_id) references tanks(station_id, id),
  unique (station_id, id)
);

-- Price history. The current price is the latest effective_at <= now().
create table prices (
  id            uuid primary key default gen_random_uuid(),
  station_id    uuid not null references stations(id) on delete cascade,
  product_id    uuid not null,
  price         numeric(12,2) not null check (price > 0),
  effective_at  timestamptz not null default now(),
  published_by  uuid references auth.users(id),
  created_at    timestamptz not null default now(),
  foreign key (station_id, product_id) references products(station_id, id)
);
create index on prices (station_id, product_id, effective_at desc);

-- What customers see: availability with its source and time (no sensors => computed from book stock or manual).
create table product_availability (
  station_id  uuid not null references stations(id) on delete cascade,
  product_id  uuid not null,
  status      availability_status not null,
  source      data_source not null,
  updated_at  timestamptz not null default now(),
  updated_by  uuid references auth.users(id),
  primary key (station_id, product_id),
  foreign key (station_id, product_id) references products(station_id, id)
);

-- ---------- company (B2B credit) accounts ----------
create table company_accounts (
  id            uuid primary key default gen_random_uuid(),
  station_id    uuid not null references stations(id) on delete cascade,
  name          text not null,
  credit_limit  numeric(16,2) not null check (credit_limit >= 0),
  status        company_status not null default 'active',
  billing_day   smallint not null default 1 check (billing_day between 1 and 28),
  qr_token      text unique,                        -- printed on driver cards
