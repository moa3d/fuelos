);

create table company_drivers (
  id                  uuid primary key default gen_random_uuid(),
  company_account_id  uuid not null references company_accounts(id) on delete cascade,
  full_name           text not null,
  phone               text,
  is_authorized       boolean not null default true
);

create table vehicles (
  id                  uuid primary key default gen_random_uuid(),
  customer_id         uuid references customers(id) on delete cascade,
  company_account_id  uuid references company_accounts(id) on delete cascade,
  plate               text not null,
  label               text,                         -- 'كيا ريو 2019'
  is_active           boolean not null default true,
  created_at          timestamptz not null default now(),
  check ((customer_id is null) <> (company_account_id is null))
);
create index on vehicles (plate);

-- ---------- shifts & sales ----------
create table shifts (
  id                 uuid primary key default gen_random_uuid(),   -- may be generated on the device
  station_id         uuid not null references stations(id),
  pump_id            uuid not null,
  attendant_id       uuid not null references auth.users(id),
  opened_at          timestamptz not null default now(),
  closed_at          timestamptz,
  opening_cash       numeric(16,2) not null default 0 check (opening_cash >= 0),
  counted_cash       numeric(16,2) check (counted_cash >= 0),
  status             shift_status not null default 'open',
  diff_reason        text,
  decided_by         uuid references auth.users(id),
  decided_at         timestamptz,
  decision_note      text,
  device_id          text references devices(id),
  client_created_at  timestamptz,
  created_at         timestamptz not null default now(),
  foreign key (station_id, pump_id) references pumps(station_id, id),
  unique (station_id, id)
);
-- Spec: two shifts cannot be open on the same pump at the same time.
create unique index one_open_shift_per_pump on shifts (pump_id) where status in ('open', 'reopened');

create table shift_readings (
  shift_id            uuid not null references shifts(id) on delete cascade,
  nozzle_id           uuid not null references nozzles(id),
  opening_reading     numeric(14,1) not null check (opening_reading >= 0),
  closing_reading     numeric(14,1),
  opening_photo_path  text,
  closing_photo_path  text,
  primary key (shift_id, nozzle_id),
  check (closing_reading is null or closing_reading >= opening_reading)
);

-- Individually recorded fills. NOT every fill is recorded (spec: QR/customer link is optional);
-- cash sales are derived from meter readings at shift close. Card/credit/voucher fills MUST be recorded.
create table sales (
  id                  uuid primary key,              -- generated on the device (idempotent sync)
  station_id          uuid not null references stations(id),
  shift_id            uuid not null,
  nozzle_id           uuid not null,
  liters              numeric(14,3) not null check (liters > 0),
  unit_price          numeric(12,2) not null check (unit_price > 0),
  amount              numeric(16,2) not null check (amount > 0),
  payment_method      payment_method not null,
  customer_id         uuid references customers(id),
  company_account_id  uuid,
  driver_id           uuid references company_drivers(id),
  vehicle_id          uuid references vehicles(id),
  odometer_km         int check (odometer_km >= 0),
  status              sale_status not null default 'recorded',
  void_reason         text,
  created_by          uuid not null references auth.users(id),
  device_id           text references devices(id),
  client_created_at   timestamptz not null,
  received_at         timestamptz not null default now(),
  foreign key (station_id, shift_id) references shifts(station_id, id),
  foreign key (station_id, nozzle_id) references nozzles(station_id, id),
  foreign key (station_id, company_account_id) references company_accounts(station_id, id),
  check (payment_method <> 'credit' or company_account_id is not null),
  check (status <> 'voided' or void_reason is not null)
);
create index on sales (shift_id);
create index on sales (customer_id) where customer_id is not null;
create index on sales (company_account_id) where company_account_id is not null;

