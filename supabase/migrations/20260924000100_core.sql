-- ---------- read models ----------
create view tank_book_levels with (security_invoker = true) as
select t.station_id, t.id as tank_id, t.product_id, t.capacity_l,
       coalesce(sum(m.liters), 0)::numeric(14,3) as book_l,
       round(100 * coalesce(sum(m.liters), 0) / t.capacity_l, 1) as book_pct
from tanks t
left join inventory_movements m on m.tank_id = t.id
group by t.id;

create view current_prices with (security_invoker = true) as
select distinct on (station_id, product_id) station_id, product_id, price, effective_at
from prices
where effective_at <= now()
order by station_id, product_id, effective_at desc;

-- Public data for the customer app (also for guests): station, price, availability, update time + source.
-- Owner-rights view on purpose: exposes only public columns.
create view public_station_prices as
select s.id as station_id, s.name as station_name, s.city, s.currency_code,
       p.id as product_id, p.name as product_name,
       cp.price, cp.effective_at as price_updated_at,
       pa.status as availability, pa.source as availability_source, pa.updated_at as availability_updated_at
from stations s
join products p on p.station_id = s.id and p.is_active
left join lateral (
  select price, effective_at from prices pr
  where pr.station_id = s.id and pr.product_id = p.id and pr.effective_at <= now()
  order by pr.effective_at desc limit 1
) cp on true
left join product_availability pa on pa.station_id = s.id and pa.product_id = p.id
where s.status = 'active';
